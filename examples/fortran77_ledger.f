C @file fortran77_ledger.f
C @brief ANSI FORTRAN 77 financial ledger example with savepoints.
      PROGRAM LEDG77
      INCLUDE 'fortran_orm_f77.inc'
      INTEGER IDB, IST, IERR, ILEN, K, ICHK
      DOUBLE PRECISION BAL, TOT
      LOGICAL LROW
      CHARACTER*24 ACCT
      ICHK = CMEMER + CCNNER + CSQLER + CBNDER + CSTPER + CTYPER +
     1       CNTFND + CVALER + CNULPT + CCONER + CTIMER + CTRUNC +
     2       CHNDER + CFULER + CBUFER + CIDXER + COPCER + CDSQLT +
     3       CDPG + CDMY + CDDB2 + CDODBC
      IF (ICHK .LE. 0) STOP 1
      CALL F7OPEN(':memory:', IDB, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7EXEC(IDB,
     1 'CREATE TABLE LEDGER(ID INT, ACCT TEXT, BAL REAL)', IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7TXBG(IDB, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7PREP(IDB, 'INSERT INTO LEDGER VALUES(?,?,?)', IST, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      DO 10 K = 1, 3
        CALL F7BINI(IST, 1, K, IERR)
        IF (IERR .NE. CORMOK) STOP 1
        CALL F7BINC(IST, 2, 'OPERATING', IERR)
        IF (IERR .NE. CORMOK) STOP 1
        CALL F7BIND(IST, 3, DBLE(K) * 125.5D0, IERR)
        IF (IERR .NE. CORMOK) STOP 1
        CALL F7STEP(IST, LROW, IERR)
        IF (IERR .NE. CORMOK) STOP 1
        CALL F7RSET(IST, IERR)
        IF (IERR .NE. CORMOK) STOP 1
   10 CONTINUE
      CALL F7FINL(IST, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7SVPT(IDB, 'BEFORE_BONUS', IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7EXEC(IDB, 'DELETE FROM LEDGER WHERE ID = 3', IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7RBSP(IDB, 'BEFORE_BONUS', IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7TXCM(IDB, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7PREP(IDB, 'SELECT ACCT, BAL FROM LEDGER', IST, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      TOT = 0.0D0
   20 CALL F7STEP(IST, LROW, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      IF (LROW) THEN
        CALL F7COLC(IST, 1, ACCT, ILEN, IERR)
        IF (IERR .NE. CORMOK) STOP 1
        CALL F7COLD(IST, 2, BAL, IERR)
        IF (IERR .NE. CORMOK) STOP 1
        TOT = TOT + BAL
        GO TO 20
      END IF
      CALL F7FINL(IST, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7CLOS(IDB, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      IF (DABS(TOT - 753.0D0) .GT. 1.0D-9) STOP 1
      WRITE (6, '(F10.2)') TOT
      END
