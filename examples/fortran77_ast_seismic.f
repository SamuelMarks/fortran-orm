C @file fortran77_ast_seismic.f
C @brief ANSI FORTRAN 77 seismic arrival catalog & 5-dialect AST example.
      PROGRAM SEIS77
      INCLUDE 'fortran_orm_f77.inc'
      INTEGER IDB, IST, IAST, IERR, ICHK, IROWID, ILEN, NNUL, NOUT, K
      DOUBLE PRECISION AMPS(3, 2), AQ(3, 2), MAG
      LOGICAL LROW, LNUL
      CHARACTER*16 STA
      CHARACTER*128 SQLBUF
      ICHK = CMEMER + CCNNER + CSQLER + CBNDER + CSTPER + CTYPER +
     1       CNTFND + CVALER + CNULPT + CCONER + CTIMER + CTRUNC +
     2       CHNDER + CFULER + CBUFER + CIDXER + COPCER + CDSQLT +
     3       CDPG + CDMY + CDDB2 + CDODBC
      IF (ICHK .LE. 0) STOP 1
      CALL F7OPEN(':memory:', IDB, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7EXEC(IDB,
     1 'CREATE TABLE SEISM(ID INT, STA TEXT, MAG REAL)', IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7EXEC(IDB, 'CREATE TABLE WAVES(TP REAL, TS REAL)', IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7PREP(IDB, 'INSERT INTO SEISM VALUES(?,?,?)', IST, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7BINI(IST, 1, 101, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7BINC(IST, 2, 'PAS', IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7BIND(IST, 3, 4.8D0, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7STEP(IST, LROW, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7RSET(IST, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7BINI(IST, 1, 102, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7BINC(IST, 2, 'ANMO', IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7BINN(IST, 3, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7STEP(IST, LROW, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7FINL(IST, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7ROW(IDB, IROWID, IERR)
      IF (IERR .NE. CORMOK .OR. IROWID .LT. 2) STOP 1
      CALL F7PREP(IDB, 'SELECT STA, MAG FROM SEISM ORDER BY ID', IST,
     1 IERR)
      IF (IERR .NE. CORMOK) STOP 1
      NNUL = 0
      MAG = 0.0D0
   10 CALL F7STEP(IST, LROW, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      IF (LROW) THEN
        CALL F7COLC(IST, 1, STA, ILEN, IERR)
        IF (IERR .NE. CORMOK .OR. ILEN .LE. 0) STOP 1
        CALL F7COLN(IST, 2, LNUL, IERR)
        IF (IERR .NE. CORMOK) STOP 1
        IF (LNUL) THEN
          NNUL = NNUL + 1
        ELSE
          CALL F7COLD(IST, 2, MAG, IERR)
          IF (IERR .NE. CORMOK) STOP 1
        END IF
        GO TO 10
      END IF
      CALL F7FINL(IST, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      IF (NNUL .NE. 1 .OR. DABS(MAG - 4.8D0) .GT. 1.0D-9) STOP 1
      DO 20 K = 1, 3
        AMPS(K, 1) = DBLE(K) * 6.2D0
        AMPS(K, 2) = DBLE(K) * 10.7D0
        AQ(K, 1) = 0.0D0
        AQ(K, 2) = 0.0D0
   20 CONTINUE
      CALL F7MATI(IDB, 'INSERT INTO WAVES VALUES(?,?)', AMPS, 3, 3, 2,
     1 IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7MATQ(IDB, 'SELECT TP, TS FROM WAVES', AQ, 3, 3, 2, NOUT,
     1 IERR)
      IF (IERR .NE. CORMOK .OR. NOUT .NE. 3) STOP 1
      CALL F7ASTS('SEISM', 2, IAST, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7ASTR(IAST, CDSQLT, SQLBUF, ILEN, IERR)
      IF (IERR .NE. CORMOK .OR. ILEN .LE. 0) STOP 1
      CALL F7ASTR(IAST, CDPG, SQLBUF, ILEN, IERR)
      IF (IERR .NE. CORMOK .OR. ILEN .LE. 0) STOP 1
      CALL F7ASTR(IAST, CDMY, SQLBUF, ILEN, IERR)
      IF (IERR .NE. CORMOK .OR. ILEN .LE. 0) STOP 1
      CALL F7ASTR(IAST, CDODBC, SQLBUF, ILEN, IERR)
      IF (IERR .NE. CORMOK .OR. ILEN .LE. 0) STOP 1
      CALL F7ASTR(IAST, CDDB2, SQLBUF, ILEN, IERR)
      IF (IERR .NE. CORMOK .OR. INDEX(SQLBUF, 'FETCH FIRST') .EQ. 0)
     1 STOP 1
      CALL F7ASTF(IAST, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7CLOS(IDB, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      WRITE (6, '(A)') SQLBUF(1:ILEN)
      END
