C @file era_06_fortran_77.f
C @brief End-to-end ANSI X3.9-1978 FORTRAN 77 ORM verification suite.
C
C Exercises F7OPEN, F7EXEC, F7TXBG, F7SVPT, F7RBSP, F7RLSP, F7TXCM,
C F7PREP, F7BINI, F7BIND, F7BINC, F7BINN, F7STEP, F7RSET, F7COLI,
C F7COLD, F7COLC, F7COLN, F7ROW, F7FINL, F7MATI, F7MATQ, F7ASTS,
C F7ASTR, F7ASTF, and F7CLOS using strict ANSI FORTRAN 77.
      PROGRAM ERA77
      INCLUDE 'fortran_orm_f77.inc'
      INTEGER IDB, IST, IAST, IERR, IV, ILEN, IRID, NOUT, ICHK
      DOUBLE PRECISION DV, DMAT(2, 2), DOUT(2, 2)
      LOGICAL LROW, LNUL
      CHARACTER*32 CNAME
      CHARACTER*128 CSQL
      ICHK = CMEMER + CCNNER + CSQLER + CBNDER + CSTPER + CTYPER +
     1       CNTFND + CVALER + CNULPT + CCONER + CTIMER + CTRUNC +
     2       CHNDER + CFULER + CBUFER + CIDXER + COPCER + CDSQLT +
     3       CDPG + CDMY + CDDB2 + CDODBC
      IF (ICHK .LE. 0) STOP 1
      CALL F7OPEN(':memory:', IDB, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7EXEC(IDB,
     1 'CREATE TABLE T77(ID INT, W REAL, NM TEXT, OPT INT)', IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7TXBG(IDB, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7TXRB(IDB, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7TXBG(IDB, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7SVPT(IDB, 'SP1', IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7RBSP(IDB, 'SP1', IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7RLSP(IDB, 'SP1', IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7PREP(IDB, 'INSERT INTO T77 VALUES(?,?,?,?)', IST, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7BINI(IST, 1, 77, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7BIND(IST, 2, 3.5D0, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7BINC(IST, 3, 'FORTRAN77   ', IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7BINN(IST, 4, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7STEP(IST, LROW, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7RSET(IST, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7FINL(IST, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7TXCM(IDB, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7ROW(IDB, IRID, IERR)
      IF (IERR .NE. CORMOK .OR. IRID .LT. 1) STOP 1
      CALL F7PREP(IDB, 'SELECT ID,W,NM,OPT FROM T77', IST, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7STEP(IST, LROW, IERR)
      IF (IERR .NE. CORMOK .OR. .NOT. LROW) STOP 1
      CALL F7COLI(IST, 1, IV, IERR)
      IF (IERR .NE. CORMOK .OR. IV .NE. 77) STOP 1
      CALL F7COLD(IST, 2, DV, IERR)
      IF (IERR .NE. CORMOK .OR. DABS(DV - 3.5D0) .GT. 1.0D-9) STOP 1
      CALL F7COLC(IST, 3, CNAME, ILEN, IERR)
      IF (IERR .NE. CORMOK .OR. ILEN .NE. 9) STOP 1
      IF (CNAME(1:9) .NE. 'FORTRAN77') STOP 1
      CALL F7COLN(IST, 1, LNUL, IERR)
      IF (IERR .NE. CORMOK .OR. LNUL) STOP 1
      CALL F7COLN(IST, 4, LNUL, IERR)
      IF (IERR .NE. CORMOK .OR. .NOT. LNUL) STOP 1
      CALL F7FINL(IST, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7EXEC(IDB, 'CREATE TABLE M77(X REAL, Y REAL)', IERR)
      IF (IERR .NE. CORMOK) STOP 1
      DMAT(1, 1) = 10.0D0
      DMAT(2, 1) = 20.0D0
      DMAT(1, 2) = 30.0D0
      DMAT(2, 2) = 40.0D0
      CALL F7MATI(IDB, 'INSERT INTO M77 VALUES(?,?)', DMAT, 2, 2, 2,
     1 IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7MATQ(IDB, 'SELECT X,Y FROM M77', DOUT, 2, 2, 2, NOUT, IERR)
      IF (IERR .NE. CORMOK .OR. NOUT .NE. 2) STOP 1
      IF (DABS(DOUT(2, 2) - 40.0D0) .GT. 1.0D-9) STOP 1
      CALL F7ASTS('M77', 5, IAST, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7ASTR(IAST, CDSQLT, CSQL, ILEN, IERR)
      IF (IERR .NE. CORMOK .OR. ILEN .LE. 0) STOP 1
      CALL F7ASTF(IAST, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7CLOS(IDB, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      WRITE (6, 100) IV
  100 FORMAT (I6)
      END
