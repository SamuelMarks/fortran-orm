C @file era_06_fortran_77.f
C @brief End-to-end ANSI X3.9-1978 FORTRAN 77 ORM verification suite
C exercising low-level F7* wrappers plus F7QINT/F7QDBL/F7QCHR, F7CNT,
C F7EXST, F7DELI, F7KVCR/F7KVPT/F7KVGT, F7VECD/F7QRYD, and F7ASAL.
      PROGRAM ERA77
      INCLUDE 'fortran_orm_f77.inc'
      INTEGER IDB, IST, IAST, IERR, IV, ILEN, IRID, NOUT, ICHK, NCNT
      DOUBLE PRECISION DV, DMAT(2, 2), DOUT(2, 2), DVEC(3), DQRY(3)
      LOGICAL LROW, LNUL, LEXST, LFOUND
      CHARACTER*32 CNAME, CKVOUT
      CHARACTER*128 CSQL
      ICHK = CMEMER + CCNNER + CSQLER + CBNDER + CSTPER + CTYPER +
     1       CNTFND + CVALER + CNULPT + CCONER + CTIMER + CTRUNC +
     2       CHNDER + CFULER + CBUFER + CIDXER + COPCER + CDSQLT +
     3       CDPG + CDMY + CDDB2 + CDODBC
      IF (ICHK .LE. 0) STOP 1
      CALL F7OPEN(':memory:', IDB, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7EXEC(IDB,
     1 'CREATE TABLE T77(ID INT, W REAL, NM TEXT, OPT INT)', IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7TXBG(IDB, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7TXRB(IDB, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7TXBG(IDB, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7SVPT(IDB, 'SP1', IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7RBSP(IDB, 'SP1', IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7RLSP(IDB, 'SP1', IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7PREP(IDB, 'INSERT INTO T77 VALUES(?,?,?,?)', IST, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7BINI(IST, 1, 77, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7BIND(IST, 2, 3.5D0, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7BINC(IST, 3, 'FORTRAN77   ', IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7BINN(IST, 4, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7STEP(IST, LROW, IERR)
      IF (IERR .NE. CORMOK .OR. LROW) STOP 1
      CALL F7RSET(IST, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7FINL(IST, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7TXCM(IDB, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7ROW(IDB, IRID, IERR)
      IF (IERR .NE. CORMOK .OR. IRID .LT. 1) STOP 1
      CALL F7PREP(IDB, 'SELECT ID,W,NM,OPT FROM T77', IST, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7STEP(IST, LROW, IERR)
      IF (IERR .NE. CORMOK .OR. .NOT. LROW) STOP 1
      CALL F7COLI(IST, 1, IV, IERR)
      IF (IERR .NE. CORMOK .OR. IV .NE. 77) STOP 1
      CALL F7COLD(IST, 2, DV, IERR)
      IF (IERR .NE. CORMOK .OR. DABS(DV - 3.5D0) .GT. 1.0D-9) STOP 1
      CALL F7COLC(IST, 3, CNAME, ILEN, IERR)
      IF (IERR .NE. CORMOK .OR. ILEN .NE. 9) STOP 1
      IF (CNAME(1:9) .NE. 'FORTRAN77') STOP 1
      CALL F7COLN(IST, 1, LNUL, IERR)
      IF (IERR .NE. CORMOK .OR. LNUL) STOP 1
      CALL F7COLN(IST, 4, LNUL, IERR)
      IF (IERR .NE. CORMOK .OR. .NOT. LNUL) STOP 1
      CALL F7FINL(IST, IERR)
      IF (IERR .NE. CORMOK) STOP 1
C Test high-level F7QINT, F7QDBL, F7QCHR, F7CNT, F7EXST, F7DELI
      CALL F7QINT(0, 'SELECT ID FROM T77', -1, IV, IERR)
      IF (IERR .EQ. CORMOK) STOP 1
      CALL F7QINT(IDB, 'SELECT OPT FROM T77', 999, IV, IERR)
      IF (IERR .NE. CORMOK .OR. IV .NE. 999) STOP 1
      CALL F7QINT(IDB, 'SELECT ID FROM T77', 0, IV, IERR)
      IF (IERR .NE. CORMOK .OR. IV .NE. 77) STOP 1
      CALL F7QDBL(0, 'SELECT W FROM T77', 0.0D0, DV, IERR)
      IF (IERR .EQ. CORMOK) STOP 1
      CALL F7QDBL(IDB, 'SELECT OPT FROM T77', 1.25D0, DV, IERR)
      IF (IERR .NE. CORMOK .OR. DABS(DV - 1.25D0) .GT. 1.0D-9) STOP 1
      CALL F7QDBL(IDB, 'SELECT W FROM T77', 0.0D0, DV, IERR)
      IF (IERR .NE. CORMOK .OR. DABS(DV - 3.5D0) .GT. 1.0D-9) STOP 1
      CALL F7QCHR(0, 'SELECT NM FROM T77', 'NONE', CNAME, ILEN, IERR)
      IF (IERR .EQ. CORMOK) STOP 1
      CALL F7QCHR(IDB, 'SELECT OPT FROM T77', 'FALLBACK', CNAME, ILEN,
     1 IERR)
      IF (IERR .NE. CORMOK .OR. CNAME(1:ILEN) .NE. 'FALLBACK') STOP 1
      CALL F7QCHR(IDB, 'SELECT NM FROM T77', 'NONE', CNAME, ILEN, IERR)
      IF (IERR .NE. CORMOK .OR. CNAME(1:ILEN) .NE. 'FORTRAN77') STOP 1
      CALL F7CNT(IDB, '   ', NCNT, IERR)
      IF (IERR .NE. CVALER) STOP 1
      CALL F7CNT(IDB, 'T77', NCNT, IERR)
      IF (IERR .NE. CORMOK .OR. NCNT .NE. 1) STOP 1
      CALL F7EXST(IDB, ' ', 'ID', 77, LEXST, IERR)
      IF (IERR .NE. CVALER) STOP 1
      CALL F7EXST(0, 'T77', 'ID', 77, LEXST, IERR)
      IF (IERR .EQ. CORMOK) STOP 1
      CALL F7EXST(IDB, 'T77', 'ID', 77, LEXST, IERR)
      IF (IERR .NE. CORMOK .OR. .NOT. LEXST) STOP 1
      CALL F7EXST(IDB, 'T77', 'ID', 88, LEXST, IERR)
      IF (IERR .NE. CORMOK .OR. LEXST) STOP 1
      CALL F7DELI(IDB, ' ', 'ID', 77, IERR)
      IF (IERR .NE. CVALER) STOP 1
      CALL F7DELI(0, 'T77', 'ID', 77, IERR)
      IF (IERR .EQ. CORMOK) STOP 1
      CALL F7DELI(IDB, 'T77', 'ID', 77, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7CNT(IDB, 'T77', NCNT, IERR)
      IF (IERR .NE. CORMOK .OR. NCNT .NE. 0) STOP 1
C Test persistent Key-Value store F7KVCR, F7KVPT, F7KVGT
      CALL F7KVCR(IDB, ' ', IERR)
      IF (IERR .NE. CVALER) STOP 1
      CALL F7KVCR(IDB, 'CFG77', IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7KVPT(IDB, ' ', 'UNIT', 'SI', IERR)
      IF (IERR .NE. CVALER) STOP 1
      CALL F7KVPT(0, 'CFG77', 'UNIT', 'SI', IERR)
      IF (IERR .EQ. CORMOK) STOP 1
      CALL F7KVPT(IDB, 'CFG77', 'UNIT', 'KELVIN', IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7KVPT(IDB, 'CFG77', 'UNIT', 'SI_KELVIN', IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7KVGT(IDB, ' ', 'UNIT', CKVOUT, ILEN, LFOUND, IERR)
      IF (IERR .NE. CVALER) STOP 1
      CALL F7KVGT(0, 'CFG77', 'UNIT', CKVOUT, ILEN, LFOUND, IERR)
      IF (IERR .EQ. CORMOK) STOP 1
      CALL F7KVGT(IDB, 'CFG77', 'MISSING', CKVOUT, ILEN, LFOUND, IERR)
      IF (IERR .NE. CORMOK .OR. LFOUND) STOP 1
      CALL F7KVGT(IDB, 'CFG77', 'UNIT', CKVOUT, ILEN, LFOUND, IERR)
      IF (IERR .NE. CORMOK .OR. .NOT. LFOUND) STOP 1
      IF (CKVOUT(1:ILEN) .NE. 'SI_KELVIN') STOP 1
C Test savepoint-guarded 1D DOUBLE vector & 2D matrix & AST
      CALL F7EXEC(IDB, 'CREATE TABLE V77(X REAL NOT NULL)', IERR)
      IF (IERR .NE. CORMOK) STOP 1
      DVEC(1) = 1.5D0
      DVEC(2) = 2.5D0
      DVEC(3) = 3.5D0
      CALL F7VECD(IDB, 'INSERT INTO V77 VALUES(?)', DVEC, 0, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7VECD(0, 'INSERT INTO V77 VALUES(?)', DVEC, 3, IERR)
      IF (IERR .EQ. CORMOK) STOP 1
      CALL F7VECD(IDB, 'BAD SQL', DVEC, 3, IERR)
      IF (IERR .EQ. CORMOK) STOP 1
      CALL F7VECD(IDB, 'INSERT INTO V77 VALUES(?,?)', DVEC, 3, IERR)
      IF (IERR .EQ. CORMOK) STOP 1
      CALL F7VECD(IDB, 'INSERT INTO V77 VALUES(NULL)', DVEC, 3, IERR)
      IF (IERR .EQ. CORMOK) STOP 1
      CALL F7VECD(IDB, 'INSERT INTO V77 VALUES(?)', DVEC, 3, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7QRYD(0, 'SELECT X FROM V77', DQRY, 3, NOUT, IERR)
      IF (IERR .EQ. CORMOK) STOP 1
      CALL F7QRYD(IDB, 'SELECT X FROM V77', DQRY, 2, NOUT, IERR)
      IF (IERR .NE. CBUFER) STOP 1
      CALL F7QRYD(IDB, 'SELECT X FROM V77', DQRY, 3, NOUT, IERR)
      IF (IERR .NE. CORMOK .OR. NOUT .NE. 3) STOP 1
      IF (DABS(DQRY(3) - 3.5D0) .GT. 1.0D-9) STOP 1
      CALL F7EXEC(IDB, 'CREATE TABLE M77(X REAL, Y REAL)', IERR)
      IF (IERR .NE. CORMOK) STOP 1
      DMAT(1, 1) = 10.0D0
      DMAT(2, 1) = 20.0D0
      DMAT(1, 2) = 30.0D0
      DMAT(2, 2) = 40.0D0
      CALL F7MATI(IDB, 'INSERT INTO M77 VALUES(?,?)', DMAT, 2, 2, 2,
     1 IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7MATQ(IDB, 'SELECT X,Y FROM M77', DOUT, 2, 2, 2, NOUT, IERR)
      IF (IERR .NE. CORMOK .OR. NOUT .NE. 2) STOP 1
      IF (DABS(DOUT(2, 2) - 40.0D0) .GT. 1.0D-9) STOP 1
      CALL F7ASTS('M77', 5, IAST, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7ASTR(IAST, CDSQLT, CSQL, ILEN, IERR)
      IF (IERR .NE. CORMOK .OR. ILEN .LE. 0) STOP 1
      CALL F7ASTF(IAST, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      CALL F7ASAL(' ', 5, CDSQLT, CSQL, ILEN, IERR)
      IF (IERR .EQ. CORMOK) STOP 1
      CALL F7ASAL('M77', 4, CDDB2, CSQL, ILEN, IERR)
      IF (IERR .NE. CORMOK .OR. ILEN .LE. 0) STOP 1
      CALL F7CLOS(IDB, IERR)
      IF (IERR .NE. CORMOK) STOP 1
      WRITE (6, 100) NOUT
  100 FORMAT (I6)
      END
