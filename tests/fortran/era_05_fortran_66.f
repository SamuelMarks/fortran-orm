C @file era_05_fortran_66.f
C @brief End-to-end ANSI X3.9-1966 FORTRAN 66 ORM verification suite
C exercising A1 & A4 Hollerith, transactions, scalar queries, 1D vectors,
C 2D matrices, persistent (X,Y) interpolation tables, and A1 codecs.
      INTEGER IURL(8), IDDL(22), IINS(28), ISEL(20)
      INTEGER IMDDL(20), IMINS(26), IMSEL(18)
      INTEGER IVDDL(18), IVINS(24), IVSEL(16), IBAD(7), ITRG(73)
      INTEGER IHURL(2), IHDDL(5), IHINS(6), IHSEL(4), IHTAG(1), IHOUT(2)
      INTEGER ITXT(3), IOUT(8), IDIG(6)
      INTEGER IDB, IDBA, IST, IERR, IHAS, IV, ILEN, NOUT, IRWID, IC6ALN
      DOUBLE PRECISION DV, DMAT(2, 2), MQ(2, 2), DVEC(3), DQRY(3)
      DOUBLE PRECISION XLUT(3), YLUT(3), YINT
      DATA IURL /58, 109, 101, 109, 111, 114, 121, 58/
      DATA IDDL /67,82,69,65,84,69,32,84,65,66,76,69,32,84,54,40,
     1           73,44,68,44,83,41/
      DATA IINS /73,78,83,69,82,84,32,73,78,84,79,32,84,54,32,86,
     1           65,76,85,69,83,40,63,44,63,44,63,41/
      DATA ISEL /83,69,76,69,67,84,32,73,44,68,44,83,32,70,82,79,
     1           77,32,84,54/
      DATA IMDDL /67,82,69,65,84,69,32,84,65,66,76,69,32,77,54,40,
     1            65,44,66,41/
      DATA IMINS /73,78,83,69,82,84,32,73,78,84,79,32,77,54,32,86,
     1            65,76,85,69,83,40,63,44,63,41/
      DATA IMSEL /83,69,76,69,67,84,32,65,44,66,32,70,82,79,77,32,
     1            77,54/
      DATA IVDDL /67,82,69,65,84,69,32,84,65,66,76,69,32,86,54,40,
     1            88,41/
      DATA IVINS /73,78,83,69,82,84,32,73,78,84,79,32,86,54,32,86,
     1            65,76,85,69,83,40,63,41/
      DATA IVSEL /83,69,76,69,67,84,32,88,32,70,82,79,77,32,86,54/
      DATA IBAD /66, 65, 68, 32, 83, 81, 76/
      DATA ITRG /67,82,69,65,84,69,32,84,82,73,71,71,69,82,32,76,54,
     1           84,32,66,69,70,79,82,69,32,73,78,83,69,82,84,32,79,
     2           78,32,76,54,32,66,69,71,73,78,32,83,69,76,69,67,84,
     3           32,82,65,73,83,69,40,65,66,79,82,84,44,39,88,39,41,
     4           59,32,69,78,68/
      DATA ITXT /70, 54, 54/
      IDB = 0
      CALL C6OPEN(IURL, 8, IDB, IERR)
      IF (IERR .NE. 0) STOP 1
      CALL C6EXEC(IDB, IDDL, 22, IERR)
      IF (IERR .NE. 0) STOP 1
C Verify C6QINT & C6QDBL defaults on empty table + invalid DB
      CALL C6QINT(0, ISEL, 20, 42, IV, IERR)
      IF (IERR .EQ. 0) STOP 1
      CALL C6QINT(IDB, ISEL, 20, 42, IV, IERR)
      IF (IERR .NE. 0 .OR. IV .NE. 42) STOP 1
      CALL C6QDBL(0, ISEL, 20, 1.5D0, DV, IERR)
      IF (IERR .EQ. 0) STOP 1
      CALL C6QDBL(IDB, ISEL, 20, 1.5D0, DV, IERR)
      IF (IERR .NE. 0 .OR. DABS(DV - 1.5D0) .GT. 1.0D-9) STOP 1
      CALL C6TXBG(IDB, IERR)
      IF (IERR .NE. 0) STOP 1
      CALL C6TXRB(IDB, IERR)
      IF (IERR .NE. 0) STOP 1
      CALL C6TXBG(IDB, IERR)
      IF (IERR .NE. 0) STOP 1
      CALL C6PREP(IDB, IINS, 28, IST, IERR)
      IF (IERR .NE. 0) STOP 1
      CALL C6BINI(IST, 1, 1966, IERR)
      IF (IERR .NE. 0) STOP 1
      CALL C6BIND(IST, 2, 6.25D0, IERR)
      IF (IERR .NE. 0) STOP 1
      CALL C6BINA(IST, 3, ITXT, 3, IERR)
      IF (IERR .NE. 0) STOP 1
      CALL C6STEP(IST, IHAS, IERR)
      IF (IERR .NE. 0) STOP 1
      CALL C6FINL(IST, IERR)
      IF (IERR .NE. 0) STOP 1
      CALL C6TXCM(IDB, IERR)
      IF (IERR .NE. 0) STOP 1
      CALL C6RWID(IDB, IRWID, IERR)
      IF (IERR .NE. 0 .OR. IRWID .NE. 1) STOP 1
      CALL C6QINT(IDB, ISEL, 20, 0, IV, IERR)
      IF (IERR .NE. 0 .OR. IV .NE. 1966) STOP 1
      CALL C6PREP(IDB, ISEL, 20, IST, IERR)
      IF (IERR .NE. 0) STOP 1
      CALL C6STEP(IST, IHAS, IERR)
      IF (IERR .NE. 0 .OR. IHAS .NE. 1) STOP 1
      CALL C6COLI(IST, 1, IV, IERR)
      IF (IERR .NE. 0 .OR. IV .NE. 1966) STOP 1
      CALL C6COLD(IST, 2, DV, IERR)
      IF (IERR .NE. 0 .OR. DABS(DV - 6.25D0) .GT. 1.0D-9) STOP 1
      CALL C6COLA(IST, 3, IOUT, 8, ILEN, IERR)
      IF (IERR .NE. 0 .OR. ILEN .NE. 3 .OR. IOUT(1) .NE. 70) STOP 1
      CALL C6FINL(IST, IERR)
      IF (IERR .NE. 0) STOP 1
C 1D vector batching & 2D matrix
      CALL C6EXEC(IDB, IVDDL, 18, IERR)
      IF (IERR .NE. 0) STOP 1
      DVEC(1) = 10.0D0
      DVEC(2) = 20.0D0
      DVEC(3) = 30.0D0
      CALL C6VECD(IDB, IVINS, 24, DVEC, 0, IERR)
      IF (IERR .NE. 0) STOP 1
      CALL C6VECD(0, IVINS, 24, DVEC, 3, IERR)
      IF (IERR .EQ. 0) STOP 1
      CALL C6VECD(IDB, IBAD, 7, DVEC, 3, IERR)
      IF (IERR .EQ. 0) STOP 1
      CALL C6VECD(IDB, IVINS, 24, DVEC, 3, IERR)
      IF (IERR .NE. 0) STOP 1
      CALL C6QRYD(0, IVSEL, 16, DQRY, 3, NOUT, IERR)
      IF (IERR .EQ. 0) STOP 1
      CALL C6QRYD(IDB, IVSEL, 16, DQRY, 2, NOUT, IERR)
      IF (IERR .NE. 34) STOP 1
      CALL C6QRYD(IDB, IVSEL, 16, DQRY, 3, NOUT, IERR)
      IF (IERR .NE. 0 .OR. NOUT .NE. 3) STOP 1
      CALL C6QDBL(IDB, IVSEL, 16, 0.0D0, DV, IERR)
      IF (IERR .NE. 0 .OR. DABS(DV - 10.0D0) .GT. 1.0D-9) STOP 1
      CALL C6EXEC(IDB, IMDDL, 20, IERR)
      IF (IERR .NE. 0) STOP 1
      DMAT(1, 1) = 1.0D0
      DMAT(2, 1) = 2.0D0
      DMAT(1, 2) = 3.0D0
      DMAT(2, 2) = 4.0D0
      CALL C6MATI(IDB, IMINS, 26, DMAT, 2, 2, 2, IERR)
      IF (IERR .NE. 0) STOP 1
      CALL C6MATQ(IDB, IMSEL, 18, MQ, 2, 2, 2, NOUT, IERR)
      IF (IERR .NE. 0 .OR. NOUT .NE. 2) STOP 1
      IF (DABS(MQ(2, 2) - 4.0D0) .GT. 1.0D-9) STOP 1
C Lookup & linear interpolation table L6
      XLUT(1) = 0.0D0
      XLUT(2) = 10.0D0
      XLUT(3) = 20.0D0
      YLUT(1) = 100.0D0
      YLUT(2) = 200.0D0
      YLUT(3) = 400.0D0
      CALL C6KVIN(IDB, XLUT, YLUT, 0, IERR)
      IF (IERR .NE. 0) STOP 1
      CALL C6KVIT(IDB, 5.0D0, YINT, IERR)
      IF (IERR .NE. 7) STOP 1
      CALL C6KVIN(0, XLUT, YLUT, 3, IERR)
      IF (IERR .EQ. 0) STOP 1
      CALL C6KVIN(IDB, XLUT, YLUT, 3, IERR)
      IF (IERR .NE. 0) STOP 1
      CALL C6KVIT(0, 5.0D0, YINT, IERR)
      IF (IERR .EQ. 0) STOP 1
      CALL C6KVIT(IDB, -2.0D0, YINT, IERR)
      IF (IERR .NE. 0 .OR. DABS(YINT - 100.0D0) .GT. 1.0D-9) STOP 1
      CALL C6KVIT(IDB, 5.0D0, YINT, IERR)
      IF (IERR .NE. 0 .OR. DABS(YINT - 150.0D0) .GT. 1.0D-9) STOP 1
      CALL C6KVIT(IDB, 25.0D0, YINT, IERR)
      IF (IERR .NE. 0 .OR. DABS(YINT - 400.0D0) .GT. 1.0D-9) STOP 1
      ISEL(8) = 83
      CALL C6QRYD(IDB, ISEL, 20, DQRY, 3, NOUT, IERR)
      IF (IERR .EQ. 0) STOP 1
      CALL C6EXEC(IDB, ITRG, 73, IERR)
      IF (IERR .NE. 0) STOP 1
      CALL C6KVIN(IDB, XLUT, YLUT, 3, IERR)
      IF (IERR .EQ. 0) STOP 1
C A1 integer/string utilities IC6ALN & C6I2A1
      IF (IC6ALN(IOUT, 0) .NE. 0) STOP 1
      IF (IC6ALN(IOUT, 8) .NE. 3) STOP 1
      CALL C6I2A1(-1, IDIG, 6, ILEN, IERR)
      IF (IERR .NE. 26) STOP 1
      CALL C6I2A1(1966, IDIG, 3, ILEN, IERR)
      IF (IERR .NE. 26) STOP 1
      CALL C6I2A1(1966, IDIG, 4, ILEN, IERR)
      IF (IERR .NE. 0 .OR. ILEN .NE. 4) STOP 1
      CALL C6I2A1(1966, IDIG, 6, ILEN, IERR)
      IF (IERR .NE. 0 .OR. ILEN .NE. 4 .OR. IDIG(6) .NE. 32) STOP 1
      CALL C6CLOS(IDB, IERR)
      IF (IERR .NE. 0) STOP 1
C Packed A4 Hollerith suite C6PKA4, C6OPA4, C6EXA4, C6PRA4, C6BNA4, C6CLA4
      CALL C6PKA4(IURL, 8, IHURL, 0)
      CALL C6PKA4(IURL, 8, IHURL, 2)
      CALL C6PKA4(IVDDL, 18, IHDDL, 5)
      CALL C6PKA4(IVINS, 24, IHINS, 6)
      CALL C6PKA4(IVSEL, 16, IHSEL, 4)
      CALL C6PKA4(ITXT, 3, IHTAG, 1)
      IDBA = 0
      CALL C6OPA4(IHURL, 8, IDBA, IERR)
      IF (IERR .NE. 0) STOP 1
      CALL C6EXA4(IDBA, IHDDL, 18, IERR)
      IF (IERR .NE. 0) STOP 1
      CALL C6PRA4(IDBA, IHINS, 24, IST, IERR)
      IF (IERR .NE. 0) STOP 1
      CALL C6BNA4(IST, 1, IHTAG, 4, IERR)
      IF (IERR .NE. 0) STOP 1
      CALL C6STEP(IST, IHAS, IERR)
      IF (IERR .NE. 0) STOP 1
      CALL C6FINL(IST, IERR)
      IF (IERR .NE. 0) STOP 1
      CALL C6PRA4(IDBA, IHSEL, 16, IST, IERR)
      IF (IERR .NE. 0) STOP 1
      CALL C6STEP(IST, IHAS, IERR)
      IF (IERR .NE. 0 .OR. IHAS .NE. 1) STOP 1
      CALL C6CLA4(IST, 1, IHOUT, 8, ILEN, IERR)
      IF (IERR .NE. 0 .OR. ILEN .NE. 3) STOP 1
      CALL C6FINL(IST, IERR)
      IF (IERR .NE. 0) STOP 1
      CALL C6CLOS(IDBA, IERR)
      IF (IERR .NE. 0) STOP 1
      WRITE (6, 100) IV
  100 FORMAT (I6)
      STOP
      END
